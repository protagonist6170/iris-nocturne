"""Render the ghostty theme format from shared colors."""


def ghostty_theme(colors: dict[str, str], ansi: list[str]) -> str:
    """Render the terminal background, selection, cursor, and ANSI palette."""
    values = {
        "background": colors["background"],
        "foreground": colors["foreground"],
        "cursor-color": colors["accent"],
        "cursor-text": colors["background"],
        "selection-background": colors["selection"],
        "selection-foreground": colors["foreground"],
    }
    lines = ["# Iris Nocturne; generated by iris-nocturne/build.py."]
    lines.extend(f"{key} = {value}" for key, value in values.items())
    lines.extend(
        f"palette = {index}={value}" for index, value in enumerate(ansi)
    )
    return "\n".join(lines) + "\n"

