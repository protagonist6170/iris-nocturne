"""Render a complete truecolor LS_COLORS policy for native consumers."""


def shell_colors(colors: dict[str, str]) -> str:
    """Replace inherited styles, including privileged file indicators."""
    indicators = {
        "no": "foreground",
        "fi": "foreground",
        "di": "type",
        "ln": "comment",
        "or": "error",
        "mi": "error",
        "ex": "added",
        "pi": "number",
        "do": "number",
        "so": "number",
        "bd": "number",
        "cd": "number",
        "su": "warning",
        "sg": "warning",
        "ca": "warning",
        "mh": "foreground",
        "tw": "type",
        "ow": "type",
        "st": "type",
    }
    categories = {
        "preprocessor": (
            "png jpg jpeg gif webp avif heic heif bmp svg ico tif tiff"
        ),
        "warning": (
            "mp3 flac wav ogg opus m4a aac aiff mp4 mkv mov webm avi m4v"
        ),
        "constant": (
            "zip rar 7z tar gz tgz bz2 tbz tbz2 xz txz zst zstd lz lzma "
            "cpio arj xar cab"
        ),
        "added": "pdf doc docx rtf odt",
    }

    def style(role: str) -> str:
        value = colors[role].lstrip("#")
        return "38;2;" + ";".join(
            str(int(value[i : i + 2], 16)) for i in (0, 2, 4)
        )

    entries = [
        f"{indicator}={style(role)}" for indicator, role in indicators.items()
    ]
    for role, extensions in categories.items():
        for extension in extensions.split():
            entries.append(f"*.{extension}={style(role)}")
    return (
        "# Generated by iris-nocturne/build.py; load before completion setup.\n"
        "export LS_COLORS='" + ":".join(entries) + "'\n"
    )
