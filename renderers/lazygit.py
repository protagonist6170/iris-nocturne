"""Render lazygit UI colors and shared file icons as a config overlay."""

import json
import pathlib

import theme_source


def lazygit_theme(
    colors: dict[str, str],
    file_icons: dict[str, list[theme_source.FileIcon]],
    filename_spellings: list[str],
) -> str:
    """Build the selected A palette without changing Git or editor settings.

    Native filename matches precede extensions and are case-sensitive. Cover
    known spellings explicitly; directory purpose icons win shared-name ties,
    as in lsd. Unmatched names retain lazygit's native fallback.
    """
    c = colors
    theme = {
        "activeBorderColor": [c["accent"], "bold"],
        "inactiveBorderColor": [c["terminal_border"]],
        "searchingActiveBorderColor": [c["warning"], "bold"],
        "optionsTextColor": [c["type"]],
        "selectedLineFgColor": ["bold"],
        "selectedLineBgColor": [c["terminal_raised"]],
        "inactiveViewSelectedLineBgColor": [c["terminal_surface"]],
        "cherryPickedCommitFgColor": [c["background"]],
        "cherryPickedCommitBgColor": [c["member"]],
        # Native fields; 0.66.2's rebase annotation still uses ANSI yellow.
        "markedBaseCommitFgColor": [c["background"]],
        "markedBaseCommitBgColor": [c["warning"]],
        "unstagedChangesColor": [c["deleted"]],
        "defaultFgColor": [c["foreground"]],
    }
    filenames = {
        icon["name"]: icon
        for category in ("files", "dirs")
        for icon in file_icons[category]
    }
    extensions = {"." + icon["name"]: icon for icon in file_icons["exts"]}
    for spelling in filename_spellings:
        icon = filenames.get(spelling.lower()) or extensions.get(
            pathlib.PurePosixPath(spelling).suffix.lower()
        )
        if icon is not None:
            filenames[spelling] = icon
    lines = [
        "# Generated by iris-nocturne/build.py; load after your base config.",
        "# Targets lazygit 0.66.2. Icons require a Nerd Font 3 font.",
        "gui:",
        '  nerdFontsVersion: "3"',
        "  showFileIcons: true",
        "  theme:",
    ]
    lines.extend(
        f"    {key}: {json.dumps(value)}" for key, value in theme.items()
    )
    lines.append("  customIcons:")
    for category, entries in (
        ("filenames", filenames), ("extensions", extensions)
    ):
        lines.append(f"    {category}:")
        for name, icon in sorted(entries.items()):
            value = {"icon": icon["text"], "color": icon["fg"]}
            lines.append(
                f"      {json.dumps(name, ensure_ascii=False)}: "
                f"{json.dumps(value, ensure_ascii=False)}"
            )
    return "\n".join(lines) + "\n"
