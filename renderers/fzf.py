"""Render shared fzf/fzf-tab UI colors without behavior flags."""


def shell_colors(colors: dict[str, str]) -> str:
    """Expose one quoted --color argument for either consumer to append."""
    c = colors
    roles = {
        "fg": c["foreground"],
        "bg": "-1",
        "fg+": "-1",
        "bg+": c["terminal_raised"],
        "hl": c["accent"],
        "hl+": c["accent"],
        "pointer": c["type"],
        "marker": c["warning"],
        "prompt": c["type"],
        "query": c["foreground"],
        "info": c["muted"],
        "spinner": c["member"],
        "header": c["member"],
        "border": c["subtle"],
        "gutter": "-1",
        "preview-fg": c["foreground"],
        "preview-bg": "-1",
        "preview-border": c["subtle"],
        "preview-scrollbar": c["subtle"],
    }
    argument = "--color=dark," + ",".join(
        f"{key}:{value}" for key, value in roles.items()
    )
    return (
        "# Generated by iris-nocturne/build.py; append to consumer options.\n"
        f"IRIS_NOCTURNE_FZF_COLORS='{argument}'\n"
    )
