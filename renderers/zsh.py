"""Render foreground-only Zsh highlighter and suggestion settings."""


def shell_styles(colors: dict[str, str]) -> str:
    """Apply after plugins, including an in-memory theme for nested commands."""
    groups = {
        "foreground": (
            "default variable assign for-loop-variable mathvar case-input "
            "back-quoted-argument recursive-base"
        ),
        "function_reference": (
            "command builtin function alias suffix-alias global-alias "
            "precommand hashed-command subcommand"
        ),
        "string": (
            "single-quoted-argument double-quoted-argument "
            "dollar-quoted-argument here-string-text "
            "case-condition optarg-string"
        ),
        "comment": "comment",
        "member": (
            "path path-to-dir single-hyphen-option double-hyphen-option "
            "back-dollar-quoted-argument "
            "back-or-dollar-double-quoted-argument here-string-var"
        ),
        "number": "mathnum for-loop-number optarg-number",
        "operator": (
            "commandseparator redirection here-string-tri "
            "for-loop-operator globbing globbing-ext history-expansion"
        ),
        "punctuation": (
            "path_pathseparator assign-array-bracket for-loop-separator "
            "case-parentheses single-sq-bracket double-sq-bracket "
            "exec-descriptor"
        ),
        "error": "unknown-token matherr incorrect-subtle",
        "accent": "paired-bracket correct-subtle",
        "subtle": "subtle-separator subtle-bg",
        "type": "bracket-level-1",
        "keyword": "reserved-word double-paren bracket-level-2",
        "hint": "bracket-level-3",
    }
    lines = [
        "# Generated by iris-nocturne/build.py; source after Zsh plugins.",
        f"typeset -g ZSH_AUTOSUGGEST_HIGHLIGHT_STYLE='fg={colors['subtle']}'",
        "if (( ${+FAST_HIGHLIGHT_STYLES} )); then",
        "  () {",
        "    emulate -L zsh",
        "    local key prefix",
        '    local -a prefixes=( "" "${FAST_THEME_NAME-}" iris-nocturne )',
        "    for key in ${(k)FAST_HIGHLIGHT_STYLES}; do",
        '      [[ $key == *default ]] && prefixes+=( "${key%default}" )',
        "    done",
        "    local -A styles=(",
    ]
    for role, keys in groups.items():
        for key in keys.split():
            attributes = ",underline" if key == "path-to-dir" else ""
            attributes += ",bold" if role == "error" else ""
            lines.append(f"      {key} 'fg={colors[role]}{attributes}'")
    lines.extend(
        [
            "    )",
            '    for prefix in "${(@u)prefixes}"; do',
            "      for key in ${(k)styles}; do",
            '        FAST_HIGHLIGHT_STYLES[${prefix}${key}]="${styles[$key]}"',
            "      done",
            "      # Keep nested highlighting independent of theme caches.",
            "      FAST_HIGHLIGHT_STYLES[${prefix}secondary]=iris-nocturne",
            "    done",
            "  }",
            "fi",
        ]
    )
    return "\n".join(lines) + "\n"
