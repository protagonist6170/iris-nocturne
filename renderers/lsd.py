"""Render lsd metadata and glyph themes without changing application options."""

import json


def color_theme(colors: dict[str, str]) -> str:
    """Use lsd's native RGB sequences; file names are handled by LS_COLORS."""
    fields: dict[str, str | dict[str, str]] = {
        "user": "foreground",
        "group": "muted",
        "tree-edge": "subtle",
        "permission": {
            "read": "warning",
            "write": "error",
            "exec": "added",
            "exec-sticky": "keyword",
            "no-access": "subtle",
            "octal": "member",
            "acl": "info",
            "context": "comment",
        },
        "date": {"hour-old": "added", "day-old": "member", "older": "muted"},
        "size": {
            "none": "subtle",
            "small": "foreground",
            "medium": "warning",
            "large": "preprocessor",
        },
        "inode": {"valid": "muted", "invalid": "subtle"},
        "links": {"valid": "muted", "invalid": "subtle"},
        "git-status": {
            "default": "muted",
            "unmodified": "muted",
            "ignored": "subtle",
            "new-in-index": "added",
            "new-in-workdir": "added",
            "typechange": "changed",
            "deleted": "deleted",
            "renamed": "changed",
            "modified": "changed",
            "conflicted": "error",
        },
    }

    def rgb(role: str) -> str:
        value = colors[role].lstrip("#")
        return str([int(value[i : i + 2], 16) for i in (0, 2, 4)])

    lines = [
        "# Generated by iris-nocturne/build.py; select color.theme: custom."
    ]
    for key, value in fields.items():
        if isinstance(value, dict):
            lines.append(key + ":")
            lines.extend(
                f"  {name}: {rgb(role)}" for name, role in value.items()
            )
        else:
            lines.append(f"{key}: {rgb(value)}")
    return "\n".join(lines) + "\n"


def icon_theme(icons: dict[str, dict[str, str]]) -> str:
    """Quote map keys as YAML strings; colors come from the filename style."""
    lines = [
        "# Generated by iris-nocturne/build.py; glyphs require Nerd Font.",
        "# Built-in lsd 1.2.0 keys, shared language icons and purpose icons.",
    ]
    for category, entries in icons.items():
        lines.append(category + ":")
        for name, glyph in sorted(entries.items()):
            lines.append(
                f"  {json.dumps(name, ensure_ascii=False)}: "
                f"{json.dumps(glyph, ensure_ascii=False)}"
            )
    return "\n".join(lines) + "\n"
